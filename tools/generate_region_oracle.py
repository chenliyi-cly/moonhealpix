"""Offline geometry references; never imports MoonHEALPix.
Requires astropy-healpix==1.1.3 and spherical-geometry==1.3.3.
Regeneration is optional; committed fixtures run without Python dependencies.
"""
import argparse, math, json, hashlib, re
from pathlib import Path
import numpy as np
from astropy_healpix import HEALPix
from astropy import units as u
from astropy.coordinates import angular_separation
from spherical_geometry.polygon import SphericalPolygon

def f(v):
    s=repr(float(v))
    if 'e' in s and '.' not in s.split('e')[0]: s=s.replace('e','.0e')
    return s

def ints(v): return '['+','.join(str(int(x)) for x in v)+']'
def generate():
    lines=['// Generated by tools/generate_region_oracle.py; independent upstream values.']
    metrics={'astropy_healpix':'1.1.3','spherical_geometry':'1.3.3','disc_cases':0,'polygon_cases':0,'cap_points':0}
    for ns in [1,2,4,8]:
        hp=HEALPix(nside=ns,order='nested')
        lon,lat=hp.healpix_to_lonlat(np.arange(12*ns*ns))
        for lo,la,rad in [(359.9,0,8),(17,89.1,3),(179,-74,17),(240,23,49),(0,-90,0),(20,10,125)]:
            selected=np.flatnonzero(angular_separation(lo*u.deg,la*u.deg,lon,lat).to_value(u.rad)<=math.radians(rad))
            overlaps=hp.cone_search_lonlat(lo*u.deg,la*u.deg,rad*u.deg)
            lines += ['///|',f'test "independent disc centers and footprint inclusion n{ns} case{metrics["disc_cases"]}" {{',f'  let g = Grid::new({ns})',f'  let center = LonLat::degrees({f(lo)}, {f(la)})',f'  let expected : Array[Int32] = {ints(selected)}',f'  assert_eq(g.search_disc(center, {f(math.radians(rad))}, g.npix(), 100000).pixels().pixels(g.npix()), expected)',f'  let cover = g.cover_disc(center, {f(math.radians(rad))}, 2, g.npix(), 1000000).pixels()',f'  for pixel in {ints(sorted(overlaps))} {{ assert_true(cover.contains(pixel)) }}','}']
            metrics['disc_cases']+=1
        for lons,lats,inside in [([350,15,15,350],[-10,-10,12,12],(0,0)),([13,137,251],[75,75,75],(81,89)),([100,145,140,110],[-40,-35,-10,-8],(120,-20))]:
            poly=SphericalPolygon.from_lonlat(lons,lats,center=inside,degrees=True)
            expected=np.flatnonzero([poly.contains_lonlat(float(lo),float(la),degrees=True) for lo,la in zip(lon.to_value(u.deg),lat.to_value(u.deg))])
            vertices='['+','.join('LonLat::degrees('+f(x)+','+f(y)+')' for x,y in zip(lons,lats))+']'
            lines += ['///|',f'test "spherical-geometry polygon reference n{ns} case{metrics["polygon_cases"]}" {{',f'  let g = Grid::new({ns})',f'  let polygon = SphericalPolygon::new({vertices}, 10)',f'  let expected : Array[Int32] = {ints(expected)}','  assert_eq(g.query_polygon(polygon,g.npix(),100000).pixels(g.npix()),expected)','}']
            metrics['polygon_cases']+=1
    rng=np.random.default_rng(20261113)
    for ns in [1,2,16,8192]:
        hp=HEALPix(nside=ns,order='nested')
        pixels=np.unique(np.concatenate(([0,ns*ns-1,4*ns*ns,8*ns*ns,12*ns*ns-1],rng.integers(0,12*ns*ns,24))))
        lines += ['///|',f'test "continuous face cap enclosure independent astropy n{ns}" {{',f'  let g = Grid::new({ns})']
        for pixel in pixels:
            samples=[]
            for dx,dy in [(0,0),(1,0),(0,1),(1,1),(.013,.913),(.37,.62),(.5,0),(1,.5)]:
                lo,la=hp.healpix_to_lonlat(int(pixel),dx=dx,dy=dy)
                samples.append('LonLat::new('+f(lo.to_value(u.rad))+','+f(la.to_value(u.rad))+')')
            lines += [f'  let cell = Cell::new(g,{int(pixel)})',f'  for point in [{",".join(samples)}] {{ assert_true(g.nested_center({int(pixel)}).separation(point) <= cell.bounding_radius()) }}']
            metrics['cap_points']+=len(samples)
        lines += ['}']
    text='\n'.join(lines)+'\n'
    metrics['fixture_sha256']=hashlib.sha256(text.encode()).hexdigest()
    return text,metrics

def fixture_tokens(text):
    """Ignore formatting/comments, retaining all semantic fixture tokens."""
    tokens = re.findall(r'//[^\n]*|"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z_0-9]*|[0-9]+(?:\.[0-9]*)?(?:[eE][+-]?[0-9]+)?|[^\s]', text)
    tokens = [t for t in tokens if not t.startswith('//') and t != '\ufeff']
    return [t for i, t in enumerate(tokens)
            if not (t == ',' and i + 1 < len(tokens) and tokens[i + 1] in [')', ']', '}'])]

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parents[1] / 'region_oracle_wbtest.mbt')
    parser.add_argument('--metrics', type=Path)
    parser.add_argument('--check', action='store_true', help='Read-only semantic regeneration check')
    args = parser.parse_args()
    text, metrics = generate()
    if args.check:
        if fixture_tokens(args.output.read_text(encoding='utf-8-sig')) != fixture_tokens(text):
            raise SystemExit('Region fixture differs from independent regeneration')
    else:
        args.output.write_text(text, encoding='utf-8')
    if args.metrics:
        args.metrics.write_text(json.dumps(metrics, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(metrics))