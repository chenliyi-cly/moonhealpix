"""Render offline oracle fixtures as static MoonBit white-box tests.

Run from any directory: python tools/oracle_to_moonbit.py
Use --check to verify byte-for-byte reproducibility without writing files.
Uses Python's standard library and the installed 20261028 moonfmt executable.
The oracle is never recomputed. Override the formatter with --moonfmt PATH.
Generated tests are test data, not production MoonBit code. NUNIQ is omitted.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BATCH_SIZE = 64



def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def moon_float(value: float) -> str:
    """Preserve binary64 round trips and give every mantissa a decimal point."""
    require(type(value) in (int, float), "Expected a numeric coordinate")
    value = float(value)
    require(math.isfinite(value), "Non-finite coordinate")
    mantissa, separator, exponent = repr(value).lower().partition("e")
    if "." not in mantissa:
        mantissa += ".0"
    return mantissa + (separator + exponent if separator else "")


def pixel(value: int, nside: int) -> str:
    require(type(value) is int and 0 <= value < 12 * nside * nside,
            "Invalid pixel for nside {}: {!r}".format(nside, value))
    return str(value)


def coordinates(record: dict) -> list[str]:
    lon, lat = record["lon"], record["lat"]
    literals = [moon_float(lon), moon_float(lat)]
    require(0 <= lon < 2 * math.pi and -math.pi / 2 <= lat <= math.pi / 2,
            "Coordinate outside oracle's radian ranges")
    return literals


def render(raw: bytes) -> str:
    data = json.loads(raw)
    metadata = data["metadata"]
    require(metadata["schema_version"] == 1, "Unsupported oracle schema")
    require(metadata["angle_unit"] == "radian", "Expected radians")
    require(metadata["pixel_index_base"] == 0, "Expected zero-based pixels")
    nsides = metadata["nsides"]
    require(nsides and len(set(nsides)) == len(nsides), "Invalid nside list")
    for nside in nsides:
        require(type(nside) is int and 1 <= nside <= 8192
                and nside & (nside - 1) == 0, "Unsupported nside")
    lines = [
        "// SPDX-License-Identifier: BSD-3-Clause",
        "// Generated by tools/oracle_to_moonbit.py; do not edit by hand.",
        "// Offline oracle: astropy-healpix; see tools/generate_oracle.py for provenance.",
        "// Input SHA-256: " + hashlib.sha256(raw).hexdigest(),
        "// Test fixtures only: excluded from production line counts. No runtime I/O.",
        "// NUNIQ intentionally omitted. Center tolerance: strictly < 1.0e-10 radians.",
        "// Reproduce: python tools/oracle_to_moonbit.py",
        "",
    ]
    for section in ("ang2pix", "ordering"):
        records = data[section]
        require(records and len(records) == metadata["counts"][section],
                "Oracle sample count mismatch: " + section)
        groups = defaultdict(list)
        for index, record in enumerate(records):
            nside = record["nside"]
            require(type(nside) is int and nside in nsides, "Unexpected sample nside")
            groups[nside].append((index, record))
        require(set(groups) == set(nsides), "Missing nside in " + section)
        for nside in sorted(groups):
            rows = groups[nside]
            for start in range(0, len(rows), BATCH_SIZE):
                batch = rows[start:start + BATCH_SIZE]
                lines.extend([
                    "///|",
                    'test "oracle {} nside={} batch={}" {{'.format(
                        section, nside, start // BATCH_SIZE),
                    "  let grid = Grid::new({})".format(nside),
                    "  let cases = [",
                ])
                for index, record in batch:
                    values = [str(index)]
                    if section == "ang2pix":
                        values += coordinates(record)
                        values += [pixel(record[key], nside)
                                   for key in ("ring_pixel", "nested_pixel")]
                        values += coordinates(record["ring_center"])
                        values += coordinates(record["nested_center"])
                    else:
                        values.append(pixel(record["pixel"], nside))
                    values += [pixel(record[key], nside)
                               for key in ("ring2nest", "nest2ring")]
                    lines.append("    (" + ", ".join(values) + "),")
                lines.extend(["  ]", "  for row in cases {"])
                if section == "ang2pix":
                    lines.extend([
                        "    let (sample, lon, lat, ring_pixel, nested_pixel, ring_lon, ring_lat, nested_lon, nested_lat, ring2nest, nest2ring) = row",
                        "    let point = LonLat::new(lon, lat)",
                        "    let actual_ring = grid.lonlat_to_ring(point)",
                        "    let actual_nested = grid.lonlat_to_nested(point)",
                        r'    assert_true(actual_ring == ring_pixel, msg="ang2pix[\{sample}] RING index: got \{actual_ring}, expected \{ring_pixel}")',
                        r'    assert_true(actual_nested == nested_pixel, msg="ang2pix[\{sample}] NESTED index: got \{actual_nested}, expected \{nested_pixel}")',
                        "    let ring_distance = grid.ring_center(ring_pixel).separation(LonLat::new(ring_lon, ring_lat))",
                        "    let nested_distance = grid.nested_center(nested_pixel).separation(LonLat::new(nested_lon, nested_lat))",
                        r'    assert_true(ring_distance < 1.0e-10, msg="ang2pix[\{sample}] RING center separation: \{ring_distance} radians")',
                        r'    assert_true(nested_distance < 1.0e-10, msg="ang2pix[\{sample}] NESTED center separation: \{nested_distance} radians")',
                        "    let actual_ring2nest = grid.ring_to_nested(ring_pixel)",
                        "    let actual_nest2ring = grid.nested_to_ring(nested_pixel)",
                    ])
                else:
                    lines.extend([
                        "    let (sample, pixel, ring2nest, nest2ring) = row",
                        "    // The same numeric pixel is an independent input in each ordering.",
                        "    let actual_ring2nest = grid.ring_to_nested(pixel)",
                        "    let actual_nest2ring = grid.nested_to_ring(pixel)",
                    ])
                for direction in ("ring2nest", "nest2ring"):
                    lines.append(
                        '    assert_true(actual_' + direction + ' == ' + direction
                        + ', msg="' + section + r'[\{sample}] ' + direction
                        + r': got \{actual_' + direction + r'}, expected \{'
                        + direction + '}")')
                lines.extend(["  }", "}", ""])
    return "\n".join(lines)


def formatted(source: str, moonfmt: str) -> bytes:
    """Format through stdin/stdout, without modifying any additional files."""
    result = subprocess.run([moonfmt, "-"], input=source.encode("utf-8"),
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, check=True)
    return result.stdout.replace(b"\r\n", b"\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=ROOT / "tests-data" / "oracle.json")
    parser.add_argument("--output", type=Path, default=ROOT / "oracle_wbtest.mbt")
    parser.add_argument("--check", action="store_true", help="Check output without writing")
    parser.add_argument("--moonfmt", default="moonfmt",
                        help="Formatter executable (default: moonfmt from PATH)")
    args = parser.parse_args()
    try:
        expected = formatted(render(args.input.read_bytes()), args.moonfmt)
        if args.check:
            require(args.output.read_bytes() == expected, "Generated tests are out of date")
            print("Verified {} (byte-for-byte)".format(args.output))
        else:
            require(args.input.resolve() != args.output.resolve(), "Output must not overwrite oracle")
            args.output.write_bytes(expected)
            print("Generated {} ({} test batches)".format(
                args.output, expected.count(b'\ntest "')))
    except subprocess.CalledProcessError as error:
        parser.exit(1, "error: moonfmt failed: " + error.stderr.decode("utf-8", errors="replace") + "\n")
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, "error: {}\n".format(error))


if __name__ == "__main__":
    main()
