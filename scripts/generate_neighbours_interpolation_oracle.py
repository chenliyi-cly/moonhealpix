"""Generate independent, deterministic neighbour/interpolation MoonBit fixtures.

Run with the existing oracle venv (astropy-healpix==1.1.3). No downloads, no
MoonHEALPix imports, no reproduction of the production algorithms. Writes only
neighbours_oracle_wbtest.mbt and interpolation_oracle_wbtest.mbt in --output-dir.
Use --check to verify fixture tokens without writing (moon fmt is tolerated). All expectations come from
astropy's compiled C implementation, not from round-trips through MoonHEALPix.

Upstream: https://github.com/astropy/astropy-healpix/tree/v1.1.3
PyPI sdist SHA256: f520d83abe8215d3e8e1a37b2bd91171ee36a6f55f110d5a2db863d75d81b3b7
cextern/astrometry.net/healpix.c SHA256:
254bdd3181f36606f9c5c92c2d14c478155cb0cd393b67f345e6a639d2a5bbd9
astropy_healpix/interpolation.c SHA256:
54150c2a32a95083a3aa4aa3578813f95892ef7b1c825a810a9a21096396da06
BSD-3-Clause notices: ../LICENSES; reference implementation is a dev dependency.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import re
from pathlib import Path

import astropy
import astropy.units as u
import astropy_healpix as ah
from astropy_healpix import core
import numpy as np

SEED = 20261113
NSIDES = (1, 2, 4, 16, 8192)
HEADER = """// SPDX-License-Identifier: BSD-3-Clause
// Generated by scripts/generate_neighbours_interpolation_oracle.py.
// Independent oracle: astropy-healpix 1.1.3, fixed seed 20261113.
// Test fixtures only; no runtime Python or upstream binaries.
"""


def f(value):
    value = float(value)
    assert math.isfinite(value)
    text = repr(value)
    if 'e' in text:
        mantissa, exponent = text.split('e')
        if '.' not in mantissa:
            mantissa += '.0'
        return mantissa + 'e' + exponent
    return text


def ints(values):
    return '[' + ', '.join(str(int(v)) for v in values) + ']'


def doubles(values):
    return '[' + ', '.join(f(v) for v in values) + ']'


def neighbours_samples(nside, rng):
    if nside <= 4:
        return np.arange(12 * nside * nside, dtype=np.int64)
    # Every face, all four corners, each edge in both directions, and interior.
    axes = [0, 1, nside // 2, nside - 2, nside - 1]
    samples = set(int(x) for x in rng.integers(0, 12*nside*nside, size=128))
    for face in range(12):
        # Test generation uses face coordinates solely to select seam samples.
        # Neighbour expectations themselves always come from the C oracle.
        for x in axes:
            for y in axes:
                morton = sum(((x >> b) & 1) << (2*b) | ((y >> b) & 1) << (2*b+1) for b in range(nside.bit_length()-1))
                samples.add(face*nside*nside + morton)
    return np.array(sorted(samples), dtype=np.int64)


def interpolation_samples(nside, nested, rng):
    points = [(float(a), math.asin(float(b))) for a,b in zip(rng.uniform(0, 2*math.pi, 96), rng.uniform(-1, 1, 96))]
    sample = nested[::max(1, len(nested)//16)][:16]
    lons, lats = core.healpix_to_lonlat(sample, nside, order='nested')
    # Centers and offsets across latitude/longitude ring boundaries.
    for lon, lat in zip(lons.to_value(u.rad), lats.to_value(u.rad)):
        points.append((float(lon), float(lat)))
        for epsilon in (-1e-8/nside, 1e-8/nside):
            points.append(((float(lon)+epsilon) % (2*math.pi), float(lat)+epsilon))
    special_lat = [0.0, math.asin(2/3), -math.asin(2/3), math.pi/2, -math.pi/2,
                   math.pi/2-1e-12, -math.pi/2+1e-12,
                   math.pi/2-0.1/nside, -math.pi/2+0.1/nside]
    # Use upstream centers for polar/equatorial transition rings.
    ring_pixels = [0, 1, 2, 3, 2*nside*(nside-1), 12*nside*nside-1,
                   12*nside*nside-2*nside*(nside-1)-1]
    _, ring_lats = core.healpix_to_lonlat(ring_pixels, nside, order='ring')
    for lat in ring_lats.to_value(u.rad):
        special_lat.extend([float(lat), float(lat)-1e-9/nside, float(lat)+1e-9/nside])
    seams = [0.0, 1e-13, math.nextafter(2*math.pi, 0), math.pi/4, math.pi/2,
             math.pi, 3*math.pi/2, 2*math.pi-1e-12, 0.317]
    points.extend((lon, lat) for lon in seams for lat in special_lat if abs(lat) <= math.pi/2)
    return list(dict.fromkeys(points))


def generate():
    if ah.__version__ != '1.1.3':
        raise SystemExit('Required independent oracle: astropy-healpix==1.1.3')
    rng = np.random.default_rng(SEED)
    neighbours_text = [HEADER]
    interpolation_text = [HEADER]
    stats = {'seed': SEED, 'astropy_healpix': ah.__version__, 'numpy': np.__version__, 'astropy': astropy.__version__, 'nsides': {}}
    for nside in NSIDES:
        nested = neighbours_samples(nside, rng)
        points = interpolation_samples(nside, nested, rng)
        lon = np.array([p[0] for p in points])*u.rad
        lat = np.array([p[1] for p in points])*u.rad
        for order, moon_order in [('ring', 'Ring'), ('nested', 'Nested')]:
            pixels = core.nested_to_ring(nested, nside) if order == 'ring' else nested
            with np.errstate(invalid='ignore'):
                neighbours = core.neighbours(pixels, nside, order=order)
            for start in range(0, len(pixels), 64):
                neighbours_text.append(f'\n///|\ntest "neighbours oracle nside={nside} {order} batch={start//64}" {{\n  let g = Grid::new({nside})\n  let cases = [\n')
                for i in range(start, min(start+64, len(pixels))):
                    neighbours_text.append(f'    ({int(pixels[i])}, {ints(neighbours[:,i])}),\n')
                neighbours_text.append(f'  ]\n  for (pixel, expected) in cases {{\n    assert_eq(g.neighbours(pixel, {moon_order}), expected)\n  }}\n}}\n')
            indices, weights = core.bilinear_interpolation_weights(lon, lat, nside, order=order)
            assert np.all(np.isfinite(weights)) and np.all(weights >= -1e-12)
            assert np.all(np.abs(weights.sum(axis=0)-1) < 1e-12)
            # Independent scalar values exercise weights as a stencil. For
            # small grids also call the actual upstream map sampler.
            values = np.sin(indices.astype(float)*0.17) + np.cos(indices.astype(float)*0.031)
            result = (values*weights).sum(axis=0)
            if nside <= 16:
                full_values = np.sin(np.arange(12*nside*nside)*0.17)+np.cos(np.arange(12*nside*nside)*0.031)
                np.testing.assert_allclose(core.interpolate_bilinear_lonlat(lon, lat, full_values, order=order), result, atol=1e-14)
            for start in range(0, len(points), 48):
                interpolation_text.append(f'\n///|\ntest "interpolation oracle nside={nside} {order} batch={start//48}" {{\n  let g = Grid::new({nside})\n  let cases = [\n')
                for i in range(start, min(start+48, len(points))):
                    interpolation_text.append(f'    ({f(points[i][0])}, {f(points[i][1])}, {ints(indices[:,i])}, {doubles(weights[:,i])}, {f(result[i])}),\n')
                interpolation_text.append(f'  ]\n  for (lon, lat, pixels, weights, expected) in cases {{\n    interpolation_assert_oracle(g, {moon_order}, lon, lat, pixels, weights, expected)\n  }}\n}}\n')
        stats['nsides'][nside] = {'neighbours_per_order': len(nested), 'interpolation_per_order': len(points)}
    # Missing-value expectations from actual NumPy/astropy NaN propagation.
    missing_cases = []
    for nside in [1, 2, 4, 16]:
        for order, moon_order in [('ring', 'Ring'), ('nested', 'Nested')]:
            for a, b in [(0.317, 0.271), (0.0, math.pi/2), (1.7, -math.pi/2), (0.0, 0.0)]:
                indices, weights = core.bilinear_interpolation_weights(a*u.rad, b*u.rad, nside, order=order)
                for slot in range(4):
                    values = np.ones(12*nside*nside)
                    values[indices[slot]] = np.nan
                    assert np.isnan(core.interpolate_bilinear_lonlat(a*u.rad, b*u.rad, values, order=order))
                    missing_cases.append(f'  interpolation_assert_missing({nside}, {moon_order}, {f(a)}, {f(b)}, {int(indices[slot])})\n')
    interpolation_text.append('\n///|\ntest "interpolation independent missing data oracle" {\n'+''.join(missing_cases)+'}\n')
    files = {'neighbours_oracle_wbtest.mbt': ''.join(neighbours_text), 'interpolation_oracle_wbtest.mbt': ''.join(interpolation_text)}
    stats['sha256'] = {name: hashlib.sha256(text.encode()).hexdigest() for name, text in files.items()}
    return files, stats


def fixture_tokens(text):
    """Ignore layout, comments and optional trailing commas added by moon fmt."""
    tokens = re.findall(r'//[^\n]*|"(?:\\.|[^"\\])*"|[A-Za-z_][A-Za-z_0-9]*|[0-9]+(?:\.[0-9]*)?(?:[eE][+-]?[0-9]+)?|[^\s]', text)
    tokens = [token for token in tokens if not token.startswith('//') and token != '\ufeff']
    return [token for i, token in enumerate(tokens)
            if not (token == ',' and i+1 < len(tokens) and tokens[i+1] in [')', ']', '}'])]

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, default=Path(__file__).resolve().parent.parent)
    parser.add_argument('--check', action='store_true', help='Verify reproducibility without modifying files')
    args = parser.parse_args()
    files, stats = generate()
    for name, text in files.items():
        path = args.output_dir/name
        if args.check:
            if not path.exists() or fixture_tokens(path.read_text(encoding='utf-8-sig')) != fixture_tokens(text):
                raise SystemExit(f'Fixture differs: {path}')
        else:
            path.write_bytes(text.encode())
    print(json.dumps(stats, indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
